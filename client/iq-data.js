const iqRound = (x) => {
  const f = Math.floor(x),
    d = x - f;
  return d < 0.5 ? f : d > 0.5 ? f + 1 : f % 2 === 0 ? f : f + 1;
};
function iqCountry() {
  const c =
    IQ_NORMS.countries[IQ_NORMS.default_country] ||
    Object.values(IQ_NORMS.countries)[0];
  return c;
}
function iqBand(age) {
  const c = iqCountry();
  return c
    ? c.age_bands.find((b) => age >= b.min_age && age <= b.max_age) || null
    : null;
}
function iqForm(age, n) {
  const pool = IQ_ITEMS.filter((it) => age >= it.age_min && age <= it.age_max);
  if (!pool.length) return [];
  const o = pool
    .slice()
    .sort(
      (a, b) =>
        a.difficulty - b.difficulty || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
    );
  if (n >= o.length) return o;
  if (n === 1) return [o[Math.floor(o.length / 2)]];
  const seen = new Set(),
    out = [];
  for (let i = 0; i < n; i++) {
    const k = iqRound((i * (o.length - 1)) / (n - 1));
    if (!seen.has(k)) {
      seen.add(k);
      out.push(o[k]);
    }
  }
  return out;
}
function iqClass(v) {
  const l = IQ_NORMS.classifications.slice().sort((a, b) => b[0] - a[0]);
  for (const [t, name] of l) if (v >= t) return name;
  return l[l.length - 1][1];
}
